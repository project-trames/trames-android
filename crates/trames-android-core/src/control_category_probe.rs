pub(super) fn run() -> Result<(), String> {
    for &word in WORDS {
        let mut m = Memory::default();
        m.map(0x1000, PAGE_SIZE, Permissions::RW)
            .map_err(|e| e.to_string())?;
        m.write_array(0x1000, word.to_le_bytes())
            .map_err(|e| e.to_string())?;
        m.protect(0x1000, PAGE_SIZE, Permissions::RX)
            .map_err(|e| e.to_string())?;
        let host = <Cpu as Backend>::features();
        let available = if word & 0xff000010 == 0x54000010 {
            host.hwcap2 & (1 << 44) != 0
        } else if word & 0x7e000000 == 0x74000000 {
            host.hwcap & (1 << 33) != 0
        } else {
            true
        };
        let mut e = <Cpu as Backend>::Engine::default();
        for trial in 0..16 {
            let mut state = trames_execution::Aarch64State {
                pc: 0x1000,
                sp: 0x2000,
                nzcv: trial << 28,
                tpidr_el0: 123,
                tpidr2_el0: 456,
                vectors: [u128::MAX / 3; 32],
                fpsr: 0x10,
                ..Default::default()
            };
            state.registers = std::array::from_fn(|r| {
                [0, 1, u64::MAX, 0x8000000000000000, 0x80, 0x8000][(r + trial as usize) % 6]
            });
            let mut c = Cpu::new(0, 0);
            let mut reference = trames_interpreter::Cpu::new(0, 0);
            c.restore_architectural_state(&state);
            reference.restore_architectural_state(&state);
            let actual = c.run(&mut e, &mut m, 1);
            if available {
                let expected = reference.run_slice(&mut m, 1);
                if format!("{actual:?}") != format!("{expected:?}")
                    || c.architectural_state() != reference.architectural_state()
                {
                    return Err(format!(
                        "control state {word:x}/{trial}: {actual:?}/{expected:?}"
                    ));
                }
            } else if !matches!(actual,SliceOutcome::Fault(trames_engine::CpuFault::Instruction{pc:0x1000,instruction}) if instruction==word)
                || c.architectural_state() != state
                || c.fault_retired() != 0
            {
                return Err(format!(
                    "control host admission {word:x}/{trial}: {actual:?}"
                ));
            }
            if e.stats.fallback_instructions != 0
                || m.fetch_u32(0x1000).map_err(|e| e.to_string())? != word
            {
                return Err("control fallback/text mismatch".into());
            }
        }
    }
    Ok(())
}
